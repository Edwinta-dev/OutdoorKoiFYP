import sys, glob, os, numpy as np, pandas as pd
S=sys.argv[1]; OUT=sys.argv[2]
SRC={'fwi':S+'/fwi/csv','oman':S+'/oman','idn':S+'/idn_t'}
def prof(s):
    h=s.groupby(s.index.hour).mean(); return h
def check(name, df, freq, dtcol=None):
    # df indexed by time with cols among do,ph,temp,tds ; resample to freq grid (mean)
    g=df.resample(freq).mean()
    L=[f'### {name}  (grid {freq}, n_rows_raw={len(df)}, grid_bins_with_data={int(g.notna().any(axis=1).sum())}, {df.index.min()} .. {df.index.max()})']
    rows=[]
    for c in g.columns:
        s=g[c]; ok=s.notna()
        pair=s.notna()&s.shift(1).notna()
        ac=s[pair].corr(s.shift(1)[pair]) if pair.sum()>10 else np.nan
        d=s.diff()[pair]
        rows.append((c,int(df[c].nunique()),len(df[c].dropna()),round(ac,3),float(d.abs().max()) if len(d) else np.nan,s.min(),s.max()))
    L.append('| var | distinct raw values | n | lag-1 autocorr | max abs step per grid bin | min | max |\n|---|---|---|---|---|---|---|')
    for r in rows: L.append('| '+' | '.join(str(round(x,3)) if isinstance(x,float) else str(x) for x in r)+' |')
    lim={'do':5.0,'ph':0.7,'temp':2.0,'tds':100.0}
    for c in g.columns:
        d=g[c].diff().abs(); n=int((d>lim[c]).sum()); L.append(f'- impossible-jump count {c}: {n} steps > {lim[c]} per {freq} bin ({n/max(1,d.notna().sum()):.4f} of steps)')
    if 'do' in g and g.do.notna().sum()>50:
        h=prof(g.do); L.append(f'- hourly DO: min at hour {int(h.idxmin())} ({h.min():.2f}), max at hour {int(h.idxmax())} ({h.max():.2f}); mean 04-06h {h.loc[4:6].mean():.2f} vs 13-16h {h.loc[13:16].mean():.2f}')
    if 'ph' in g and g.ph.notna().sum()>50:
        h=prof(g.ph); L.append(f'- hourly pH: min hour {int(h.idxmin())} ({h.min():.2f}), max hour {int(h.idxmax())} ({h.max():.2f})')
    if 'temp' in g and g.temp.notna().sum()>50:
        h=prof(g.temp); L.append(f'- hourly temp: min hour {int(h.idxmin())} ({h.min():.2f}), max hour {int(h.idxmax())} ({h.max():.2f})')
    if 'do' in g and 'ph' in g:
        m=g[['do','ph']].dropna()
        if len(m)>50:
            L.append(f'- within-site pH-DO: Pearson {m.corr().iloc[0,1]:.3f}, Spearman {m.corr("spearman").iloc[0,1]:.3f} (n={len(m)})')
    return '\n'.join(L), rows, g
out=['# Stage 0 integrity checks (HANDOVER s4)\n','Generated by stage0/code/integrity.py. Thresholds for "impossible jump": DO 5 mg/L, pH 0.7, temp 2 C, TDS 100 per grid bin. Expect: lag-1 >0.9, pre-dawn DO minimum, positive pH-DO.\n']
summ=[]
# FWI: raw (flags ignored, only physical range) so integrity is judged on the data as published
fw=[]
for f in sorted(glob.glob(SRC['fwi']+'/ara2_*.csv')):
    d=pd.read_csv(f); d.columns=['t','do','ph','temp','qt','qdo','qph']; d['t']=pd.to_datetime(d.t); d=d.set_index('t')[['do','ph','temp']]
    d=d.where(d>0); d.loc[(d.ph<4)|(d.ph>11),'ph']=np.nan; d.loc[(d.temp<10)|(d.temp>40),'temp']=np.nan
    t,rows,g=check(os.path.basename(f)[:-4],d,'15min'); fw.append((os.path.basename(f)[:-4],rows,g,t))
out.append('## FWI India (17 ponds, as published, zeros/out-of-range -> NaN as in load.py, QC flags not applied; time = IST)\n')
tab=['| pond | lag1 DO | lag1 pH | lag1 temp | DO min hour | pH-DO Pearson | distinct DO | jumps(DO/pH/T) |','|---|---|---|---|---|---|---|---|']
for pid,rows,g,t in fw:
    r={x[0]:x for x in rows}; h=g.do.groupby(g.index.hour).mean(); m=g[['do','ph']].dropna()
    dd=lambda c,l:int((g[c].diff().abs()>l).sum())
    tab.append(f"| {pid} | {r['do'][3]} | {r['ph'][3]} | {r['temp'][3]} | {int(h.idxmin())} | {m.corr().iloc[0,1]:.2f} | {r['do'][1]} | {dd('do',5)}/{dd('ph',.7)}/{dd('temp',2)} |")
out+=tab+['']
allg=pd.concat([g for _,_,g,_ in fw]); 
for pid,rows,g,t in fw: out+=[t,'']
# Oman
om=SRC['oman']
for nm,p in [('Oman offline open pond (raw, 5-7 s -> 5 min)','/data/raw/offline/raw_readings.csv'),('Oman live 180 L tank (raw -> 5 min)','/data/raw/live/raw_readings_new.csv')]:
    d=pd.read_csv(om+p,parse_dates=['timestamp']).set_index('timestamp').rename(columns={'do_mgL':'do','temp_c':'temp'})[['do','ph','temp']]
    t,_,_=check(nm,d,'5min'); out+=['## '+nm,t,'']
d=pd.read_csv(om+'/data/processed/aggregated_data.csv',parse_dates=['timestamp']).set_index('timestamp').rename(columns={'do_mean':'do','temp_mean':'temp','ph_mean':'ph'})[['do','ph','temp']]
t,_,_=check('Oman aggregated_data (5 min, as published)',d,'5min'); out+=['## Oman aggregated',t,'']
# IDN-T
for nm,p,enc in [('IDN-T cleaned pond_iot_2023.csv','pond_iot_2023.csv','utf-8'),('IDN-T raw pond_iot_2023_raw.csv','pond_iot_2023_raw.csv','utf-8-sig')]:
    d=pd.read_csv(SRC['idn']+'/'+p,encoding=enc); d['t']=pd.to_datetime(d.created_date,format='%m/%d/%Y %H:%M'); d=d.set_index('t').sort_index().rename(columns={'water_pH':'ph','TDS':'tds','water_temp':'temp'})[['ph','tds','temp']]
    d=d.groupby(level=0).mean()
    t,_,_=check(nm+' (no DO; time local, tz not documented)',d,'10min'); out+=['## '+nm,t,'']
open(OUT,'w',encoding='utf-8').write('\n'.join(out))
