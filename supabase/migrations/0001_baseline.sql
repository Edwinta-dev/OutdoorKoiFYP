-- 0001_baseline.sql
--
-- Baseline of the OutdoorKoi Supabase schema, reconstructed from how the
-- code in this repository reads and writes the database:
--   Backend/DigitalTwin/state_store.py   (digital twin service)
--   Backend/Camera/camera.py             (camera service)
--   Embedded/sensor_node/sensor_node.ino (ESP32 sensor node)
--   MobileUI/mobile_app/lib/             (Flutter app)
--
-- Until this file existed the schema lived only in the live project. Table
-- and column names are copied exactly from the code, including the three
-- spellings of the user column ("userID", "user_ID", userid) that coexist
-- in the live schema; quoted identifiers are case-sensitive, so do not
-- normalise them here without a migration that also changes every reader.
--
-- Anything that could not be recovered from the code is marked
--   -- RECONSTRUCTED: verify against live
-- The owner diffs this file against the live project (see
-- supabase/README.md) and records the differences in a later migration.
--
-- Not covered by this baseline (live-only, not recoverable from code):
--   * Row-level security policies and grants. The app and the sensor node
--     use the publishable (anon) key to read and write UserData,
--     pondInterventions, Fish_Database, imageTable and SensorData, and to
--     call both RPCs, so the live policies must allow at least that.
--   * The job that fetches NEA weather into weather_telemetry and
--     weather_forecasts, and any pg_cron schedules.
--
-- Every statement is idempotent (IF NOT EXISTS / OR REPLACE / ON CONFLICT)
-- so the file can be applied to a fresh project or replayed against one
-- that already has the tables without error.

-- =====================================================================
-- Telemetry from the ESP32 sensor node
-- =====================================================================

-- One row per reading. The sensor node inserts all readings from one wake
-- cycle as a single batched insert: [{sensor_type, data1}, ...] with
-- sensor_type in 'temp', 'TDS', 'pH', 'LUX'. LUX is -1 when the light
-- sensor failed that cycle.
-- RECONSTRUCTED: verify against live. The firmware sends no pond or user
-- id, so this table has no user column and every reader treats it as the
-- one instrumented pond. If the live table has a user column, add it here.
create table if not exists public."SensorData" (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null default now(),
    sensor_type text not null,
    data1       double precision
);

create index if not exists "SensorData_type_created_idx"
    on public."SensorData" (sensor_type, created_at desc);

-- Daily aggregates of SensorData, one row per user, sensor type and UTC
-- calendar day. Read by state_store.fetch_daily_sensor_stats and
-- fetch_daily_sensor_series, and by get_historical_graph_payload.
create table if not exists public.daily_sensor_averages (
    id          bigint generated by default as identity primary key,
    userid      bigint not null,
    sensor_type text not null,
    avg_value   double precision,
    min_value   double precision,
    max_value   double precision,
    record_date date not null,
    unique (userid, sensor_type, record_date)
);

-- =====================================================================
-- Pond configuration and species reference data
-- =====================================================================

-- One row per pond owner, written at onboarding (onboarding_screen.dart
-- upserts on "userID") and deleted from settings. volume is litres,
-- biomass is kilograms of fish summed over every species entry.
create table if not exists public."UserData" (
    "userID"             bigint primary key,
    created_at           timestamptz not null default now(),
    volume               double precision,
    biomass              double precision,
    latitude             double precision,
    longitude            double precision,
    manualpostallocation text,
    -- Nearest NEA station per weather metric, filled by the trigger below
    -- and returned to the app by the onboarding upsert.
    "ClosestStations"    jsonb
);

-- Species care data shown in the app's species guide. Columns match the
-- AquariumScraper CSV the table was loaded from; every value is free text
-- (ranges such as '6.0 - 7.0' and '21°C - 26°C' are parsed in the app).
create table if not exists public."Fish_Database" (
    "Title"        text primary key,
    "Product URL"  text,
    "Image URL"    text,
    "Common Name"  text,
    "Care Level"   text,
    "Maximum Size" text,
    "pH"           text,
    "Temperature"  text,
    "Life Span"    text,
    "Behaviour"    text,
    "Tank Region"  text,
    "Gender"       text
);

-- =====================================================================
-- Owner-logged interventions
-- =====================================================================

-- event_type values are upper snake case: 'FEEDING', 'WATER_CHANGE',
-- 'WATER_TOPUP', 'ALGAE_SCRUB'. Only the columns for the logged type are
-- filled; the rest stay null.
create table if not exists public."pondInterventions" (
    id                 bigint generated by default as identity primary key,
    created_at         timestamptz not null default now(),
    "userID"           bigint not null,
    event_type         text not null,
    event_timestamp    timestamptz not null default now(),
    volume_percentage  double precision,
    volume_litres      double precision,
    food_grams         double precision,
    protein_percentage double precision,
    algae_method       text
);

create index if not exists "pondInterventions_user_type_ts_idx"
    on public."pondInterventions" ("userID", event_type, event_timestamp desc);

-- =====================================================================
-- Camera frames
-- =====================================================================

-- One row per analysed ESP32-CAM frame, written by Backend/Camera/camera.py.
-- current_state is the HSV state machine's output, normally a two-element
-- array like ["base", 0.1235] (label, smoothed green-ratio baseline).
-- imageURL is the public URL of the frame in the imageAnalysisBucket bucket.
-- RECONSTRUCTED: verify against live. "user_ID" is typed bigint to match
-- the other user columns; camera.py falls back to the string
-- 'default_user' when the X-User-ID header is missing, which a bigint
-- column rejects. If the live column is text, change it here.
create table if not exists public."imageTable" (
    id            bigint generated by default as identity primary key,
    created_at    timestamptz not null default now(),
    "user_ID"     bigint,
    green_ratio   double precision,
    current_state jsonb,
    "imageURL"    text
);

create index if not exists "imageTable_user_created_idx"
    on public."imageTable" ("user_ID", created_at desc);

-- Human algae severity labels from the app's rating card.
-- green_ratio_at_rating is copied from the frame so the calibration set
-- survives imageTable rows being pruned; image_id is cleared rather than
-- the rating deleted when that happens.
-- severity is one of 'none', 'minor', 'moderate', 'severe' or
-- 'obstruction' (algae_engine.SEVERITY_LEVELS plus the blocked-view flag).
create table if not exists public.algae_severity_ratings (
    id                    bigint generated by default as identity primary key,
    userid                bigint not null,
    image_id              bigint references public."imageTable" (id) on delete set null,
    image_url             text,
    severity              text not null,
    is_obstructed         boolean not null default false,
    green_ratio_at_rating double precision,
    image_captured_at     timestamptz,
    rated_at              timestamptz not null default now(),
    notes                 text
);

create index if not exists algae_severity_ratings_user_rated_idx
    on public.algae_severity_ratings (userid, rated_at desc);

-- =====================================================================
-- NEA weather
-- =====================================================================

-- RECONSTRUCTED: verify against live. No code in this repository writes
-- these two tables; a live-only job fetches the data.gov.sg real-time
-- weather APIs into them. The shapes below are what
-- get_bundled_dashboard_payload needs to produce the keys the poller and
-- the app read.

-- Latest station readings. metric is 'air_temp', 'rainfall', 'wind_speed'
-- or 'relative_humidity'. value is in the NEA API's own unit (°C, mm,
-- knots, %).
create table if not exists public.weather_telemetry (
    id           bigint generated by default as identity primary key,
    recorded_at  timestamptz not null,
    fetched_at   timestamptz not null default now(),
    metric       text not null,
    station_id   text not null,
    station_name text,
    latitude     double precision,
    longitude    double precision,
    value        double precision,
    unique (metric, station_id, recorded_at)
);

create index if not exists weather_telemetry_metric_recorded_idx
    on public.weather_telemetry (metric, recorded_at desc);

-- Latest forecasts, one row per fetch. forecast_type is 'forecast_2hr',
-- 'forecast_24hr', 'outlook_4day' or 'uv_index'. payload holds the value
-- handed to the app unchanged:
--   forecast_2hr   {"area": ..., "forecast": "Fair (Day)"}, one row per area
--   forecast_24hr  {"general": {...}, "periods": [...]}
--   outlook_4day   [{"data": {"day", "forecast", "temperature", ...}}, ...]
--   uv_index       {"data": {"uv": 5, ...}}
-- area is set only for forecast_2hr.
create table if not exists public.weather_forecasts (
    id            bigint generated by default as identity primary key,
    fetched_at    timestamptz not null default now(),
    forecast_type text not null,
    area          text,
    valid_from    timestamptz,
    valid_to      timestamptz,
    payload       jsonb not null
);

create index if not exists weather_forecasts_type_fetched_idx
    on public.weather_forecasts (forecast_type, fetched_at desc);

