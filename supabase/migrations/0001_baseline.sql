-- Fills UserData."ClosestStations" with the nearest NEA station for each
-- weather metric, from the pond's latitude and longitude, so the dashboard
-- payload can read the readings nearest the pond. Result shape:
--   {"air_temp": "S109", "rainfall": "S77", ..., "forecast_area": "Bishan"}
-- RECONSTRUCTED: verify against live. The app only shows that a JSON
-- object comes back from the onboarding upsert; the key names, the
-- distance measure and the forecast_area lookup are written from that
-- documented behaviour.
create or replace function public.assign_closest_stations()
returns trigger
language plpgsql
as $$
declare
    stations jsonb;
begin
    if new.latitude is null or new.longitude is null then
        new."ClosestStations" := null;
        return new;
    end if;

    -- Equirectangular distance is accurate enough across Singapore.
    select jsonb_object_agg(metric, station_id)
      into stations
      from (
        select distinct on (metric) metric, station_id
          from public.weather_telemetry
         where latitude is not null and longitude is not null
         order by metric,
                  power(latitude - new.latitude, 2)
                  + power((longitude - new.longitude) * cos(radians(new.latitude)), 2),
                  recorded_at desc
      ) nearest;

    new."ClosestStations" := coalesce(stations, '{}'::jsonb)
        || jsonb_build_object('forecast_area', (
            select f.area
              from public.weather_forecasts f
             where f.forecast_type = 'forecast_2hr'
               and f.area is not null
               and f.payload ? 'latitude'
             order by power((f.payload ->> 'latitude')::double precision - new.latitude, 2)
                      + power(((f.payload ->> 'longitude')::double precision - new.longitude)
                              * cos(radians(new.latitude)), 2),
                      f.fetched_at desc
             limit 1));
    return new;
end;
$$;

drop trigger if exists "UserData_assign_closest_stations" on public."UserData";
create trigger "UserData_assign_closest_stations"
    before insert or update of latitude, longitude on public."UserData"
    for each row execute function public.assign_closest_stations();

-- Recomputes one UTC day of daily_sensor_averages from SensorData for
-- every onboarded pond. LUX readings of -1 (failed light sensor) are
-- excluded.
-- RECONSTRUCTED: verify against live. The code documents only that rows
-- are daily aggregates by UTC calendar day with gaps when the sensor was
-- offline. Because SensorData carries no user id, every pond in UserData
-- gets the same aggregate. How the live project schedules this (pg_cron,
-- trigger or external job) is not recoverable from the code.
create or replace function public.refresh_daily_sensor_averages(p_day date)
returns void
language sql
as $$
    insert into public.daily_sensor_averages
        (userid, sensor_type, avg_value, min_value, max_value, record_date)
    select u."userID", s.sensor_type, avg(s.data1), min(s.data1), max(s.data1), p_day
      from public."SensorData" s
     cross join public."UserData" u
     where s.created_at >= p_day::timestamp at time zone 'UTC'
       and s.created_at <  (p_day + 1)::timestamp at time zone 'UTC'
       and s.data1 is not null
       and not (s.sensor_type = 'LUX' and s.data1 < 0)
     group by u."userID", s.sensor_type
    on conflict (userid, sensor_type, record_date) do update
        set avg_value = excluded.avg_value,
            min_value = excluded.min_value,
            max_value = excluded.max_value;
$$;

-- Everything the dashboard and the digital twin poller need in one call.
-- Keys read by code:
--   raw_sensor        {pH, TDS, temp, LUX, recorded_at}
--                     poller.py, forecast_utils.current_conditions, the
--                     three dashboard cards
--   nea_telemetry     {air_temp, rainfall, wind_speed, relative_humidity},
--                     each {value, station_id, recorded_at}
--                     forecast_utils.current_conditions, weather ribbon,
--                     temperature card
--   nea_forecasts     {forecast_2hr, forecast_24hr, outlook_4day, uv_index,
--                      two_hr_forecast, rainfall_mm}
--                     forecast_utils, weather ribbon, forecast modal, pH and
--                     solar cards
--   telemetry_history [{time, ph, tds, tempC, lux}], oldest first
--                     dashboard_view._parseTelemetryHistory
-- The conftest.py DASHBOARD_PAYLOAD fixture is a recorded example.
-- RECONSTRUCTED: verify against live. The body is written from those
-- readers; the station choice, the 24-hour history window and the
-- per-minute grouping of a wake cycle's readings are assumptions.
create or replace function public.get_bundled_dashboard_payload(p_user_id bigint)
returns jsonb
language plpgsql
stable
as $$
declare
    stations jsonb;
    v_area   text;
    sensor   jsonb;
    weather  jsonb;
    fc       jsonb;
    history  jsonb;
begin
    select coalesce(u."ClosestStations", '{}'::jsonb)
      into stations
      from public."UserData" u
     where u."userID" = p_user_id;
    stations := coalesce(stations, '{}'::jsonb);
    v_area := stations ->> 'forecast_area';

    -- Latest reading of each sensor type.
    with latest as (
        select distinct on (sensor_type) sensor_type, data1, created_at
          from public."SensorData"
         order by sensor_type, created_at desc
    )
    select jsonb_build_object(
               'pH',   (select data1 from latest where sensor_type = 'pH'),
               'TDS',  (select data1 from latest where sensor_type = 'TDS'),
               'temp', (select data1 from latest where sensor_type = 'temp'),
               'LUX',  (select data1 from latest where sensor_type = 'LUX'),
               'recorded_at', (select max(created_at) from latest))
      into sensor;

    -- Latest reading per metric, preferring the pond's closest station.
    with latest as (
        select distinct on (metric) metric, station_id, value, recorded_at
          from public.weather_telemetry
         order by metric,
                  (station_id = stations ->> metric) desc nulls last,
                  recorded_at desc
    )
    select jsonb_build_object(
               'air_temp',          (select jsonb_build_object('value', value, 'station_id', station_id, 'recorded_at', recorded_at) from latest where metric = 'air_temp'),
               'rainfall',          (select jsonb_build_object('value', value, 'station_id', station_id, 'recorded_at', recorded_at) from latest where metric = 'rainfall'),
               'wind_speed',        (select jsonb_build_object('value', value, 'station_id', station_id, 'recorded_at', recorded_at) from latest where metric = 'wind_speed'),
               'relative_humidity', (select jsonb_build_object('value', value, 'station_id', station_id, 'recorded_at', recorded_at) from latest where metric = 'relative_humidity'))
      into weather;

    -- Latest forecast of each type; forecast_2hr for the pond's area.
    with latest as (
        select distinct on (wf.forecast_type) wf.forecast_type, wf.payload
          from public.weather_forecasts wf
         order by wf.forecast_type,
                  (wf.area = v_area) desc nulls last,
                  wf.fetched_at desc
    )
    select jsonb_build_object(
               'forecast_2hr',  (select payload from latest where forecast_type = 'forecast_2hr'),
               'forecast_24hr', (select payload from latest where forecast_type = 'forecast_24hr'),
               'outlook_4day',  coalesce((select payload from latest where forecast_type = 'outlook_4day'), '[]'::jsonb),
               'uv_index',      (select payload from latest where forecast_type = 'uv_index'))
      into fc;
    fc := fc || jsonb_build_object(
        'two_hr_forecast', fc -> 'forecast_2hr' ->> 'forecast',
        'rainfall_mm',     weather -> 'rainfall' -> 'value');

    -- Last 24 hours of readings, one entry per wake cycle.
    select coalesce(jsonb_agg(jsonb_build_object(
               'time',  cycle,
               'ph',    ph,
               'tds',   tds,
               'tempC', temp_c,
               'lux',   lux) order by cycle), '[]'::jsonb)
      into history
      from (
        select date_trunc('minute', created_at) as cycle,
               avg(data1) filter (where sensor_type = 'pH')   as ph,
               avg(data1) filter (where sensor_type = 'TDS')  as tds,
               avg(data1) filter (where sensor_type = 'temp') as temp_c,
               avg(data1) filter (where sensor_type = 'LUX' and data1 >= 0) as lux
          from public."SensorData"
         where created_at >= now() - interval '24 hours'
         group by 1
      ) cycles;

    return jsonb_build_object(
        'raw_sensor',        sensor,
        'nea_telemetry',     weather,
        'nea_forecasts',     fc,
        'telemetry_history', history);
end;
$$;

-- Daily trends and intervention markers for the detail graph screen.
-- Keys read by detail_graph_screen.dart and historical_line_chart.dart:
--   daily_trends  [{date, sensor_type, avg_value, min_value, max_value}]
--   interventions [{event_type, timestamp, is_major_reset, ...}]
-- RECONSTRUCTED: verify against live. is_major_reset is written here as
-- a water change of 50 % or more, or any algae scrub; the app only draws
-- those markers more prominently.
create or replace function public.get_historical_graph_payload(p_userid bigint, p_days integer)
returns jsonb
language sql
stable
as $$
    select jsonb_build_object(
        'daily_trends', coalesce((
            select jsonb_agg(jsonb_build_object(
                       'date',        d.record_date,
                       'sensor_type', d.sensor_type,
                       'avg_value',   d.avg_value,
                       'min_value',   d.min_value,
                       'max_value',   d.max_value) order by d.record_date)
              from public.daily_sensor_averages d
             where d.userid = p_userid
               and d.record_date >= (now() at time zone 'UTC')::date - p_days), '[]'::jsonb),
        'interventions', coalesce((
            select jsonb_agg(jsonb_build_object(
                       'id',                 i.id,
                       'event_type',         i.event_type,
                       'timestamp',          i.event_timestamp,
                       'volume_percentage',  i.volume_percentage,
                       'volume_litres',      i.volume_litres,
                       'food_grams',         i.food_grams,
                       'protein_percentage', i.protein_percentage,
                       'algae_method',       i.algae_method,
                       'is_major_reset',     (i.event_type = 'WATER_CHANGE' and coalesce(i.volume_percentage, 0) >= 50)
                                             or i.event_type = 'ALGAE_SCRUB') order by i.event_timestamp)
              from public."pondInterventions" i
             where i."userID" = p_userid
               and i.event_timestamp >= now() - make_interval(days => p_days)), '[]'::jsonb));
$$;
